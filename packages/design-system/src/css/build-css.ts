import { darkTheme } from "../themes/dark";
import { lightTheme } from "../themes/light";
import { tradeDark, tradeLight, tradeStatic } from "../themes/trade";
import { worldIdDark, worldIdFont, worldIdLight } from "../themes/world-id";
import { duration, easing, keyframes } from "../tokens/motion";
import { radius } from "../tokens/radius";
import { shadow } from "../tokens/shadow";
import { layout, space } from "../tokens/space";
import {
  fontFamily,
  fontSize,
  fontWeight,
  letterSpacing,
  lineHeight,
} from "../tokens/typography";
import { zIndex } from "../tokens/z-index";

type Tokens = Readonly<Record<string, string>>;

// Prefix each key, turning "13.5" into "13-5" so it is a valid custom property name.
function prefixed(prefix: string, tokens: Tokens): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(tokens))
    out[`${prefix}${key.replace(".", "-")}`] = value;
  return out;
}

// Theme independent tokens, emitted once in :root.
export const staticVars: Record<string, string> = {
  ...fontFamily,
  ...worldIdFont,
  ...prefixed("fs-", fontSize),
  ...prefixed("fw-", fontWeight),
  ...prefixed("lh-", lineHeight),
  ...prefixed("ls-", letterSpacing),
  ...prefixed("sp-", space),
  ...layout,
  ...radius,
  ...shadow,
  ...prefixed("dur-", duration),
  ...prefixed("ease-", easing),
  ...prefixed("z-", zIndex),
};

export const lightVars: Record<string, string> = {
  ...lightTheme,
  ...worldIdLight,
};
export const darkVars: Record<string, string> = {
  ...darkTheme,
  ...worldIdDark,
};

// Trader app overrides, scoped by an attribute on <html> or any wrapper.
export const tradeScope = '[data-app="trade"]';
export const tradeLightVars: Record<string, string> = {
  ...tradeStatic,
  ...tradeLight,
};
export const tradeDarkVars: Record<string, string> = { ...tradeDark };

// Matches the scope on the themed element itself and on any descendant.
function within(theme: string): string {
  return `${theme}${tradeScope}, ${theme} ${tradeScope}`;
}

function declarations(vars: Tokens, indent: string): string {
  return Object.entries(vars)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join("\n");
}

export function buildCss(): string {
  const frames = Object.entries(keyframes).map(
    ([name, body]) => `@keyframes ${name} { ${body} }`,
  );
  return [
    "/* Generated by @night-shares/design-system (bun run gen:css). Do not edit. */",
    `:root {\n${declarations(staticVars, "  ")}\n${declarations(lightVars, "  ")}\n  color-scheme: light;\n}`,
    `[data-theme="dark"] {\n${declarations(darkVars, "  ")}\n  color-scheme: dark;\n}`,
    "@media (prefers-color-scheme: dark) {",
    `  :root:not([data-theme="light"]) {\n${declarations(darkVars, "    ")}\n    color-scheme: dark;\n  }\n}`,
    `${tradeScope} {\n${declarations(tradeLightVars, "  ")}\n}`,
    `${within('[data-theme="dark"]')} {\n${declarations(tradeDarkVars, "  ")}\n}`,
    "@media (prefers-color-scheme: dark) {",
    `  ${within(':root:not([data-theme="light"])')} {\n${declarations(tradeDarkVars, "    ")}\n  }\n}`,
    ...frames,
    "",
  ].join("\n");
}
